def metrics_page() -> str:
    parts = [
        "# Metrics reference",
        "Every built-in metric and its options.",
        "Run `paperlab-space metrics` to list the metrics in your installed version. "
        "For how normalisation and label extraction work, see the "
        "[metrics guide](../guides/metrics.md).",
    ]
    for name, cls in sorted(available_metrics().items()):
        hints = typing.get_type_hints(cls.__init__)
        signature = inspect.signature(cls.__init__)
        rows = ["| Option | Type | Default | Description |", "| --- | --- | --- | --- |"]
        for param in list(signature.parameters.values())[1:]:
            rows.append(
                f"| `{param.name}` | {cell(type_name(hints[param.name]))} | "
                f"{cell(scalar(param.default))} | {cell(OPTIONS.get(param.name, ''))} |"
            )
        parts += [
            f"## {name}",
            md(cls.description),
            f"Needs an answer key: {'yes' if cls.requires_reference else 'no'}. "
            f"Higher is better: {'yes' if cls.higher_is_better else 'no'}.",
            "\n".join(rows),
        ]
    return HEADER + "\n\n".join(parts) + "\n"


