# --- Docstrings -------------------------------------------------------------------------


def md(text: str) -> str:
    """Convert the reST bits used in docstrings to Markdown."""
    text = re.sub(r"`([^`<]+?) <([^>]+)>`_", r"[\1](\2)", text)
    text = re.sub(r":(?:class|func|meth|attr|mod|exc):`~?([^`]+)`", r"`\1`", text)
    text = text.replace("``", "`")
    text = re.sub(r"\s*# doctest:.*$", "", text, flags=re.MULTILINE)
    blocks = []
    for block in text.split("\n\n"):
        if block.lstrip().startswith(">>>"):
            block = "```python\n" + textwrap.dedent(block).strip() + "\n```"
        blocks.append(block)
    return "\n\n".join(blocks)


def docstring_md(obj: griffe.Object) -> str:
    """A docstring as Markdown, with Google-style Args rendered as a list."""
    if obj.docstring is None:
        return ""
    parts = []
    for section in griffe.Docstring(obj.docstring.value, parser="google", parent=obj).parsed:
        if isinstance(section, griffe.DocstringSectionText):
            parts.append(md(section.value))
        elif isinstance(section, griffe.DocstringSectionParameters):
            items = [f"- `{p.name}`: {one_line(md(p.description))}" for p in section.value]
            parts.append("**Arguments**\n\n" + "\n".join(items))
    return "\n\n".join(p for p in parts if p.strip())


def one_line(text: str) -> str:
    return " ".join(text.split())


def cell(text: str) -> str:
    """Make text safe for a Markdown table cell."""
    return one_line(text).replace("|", "\\|")


