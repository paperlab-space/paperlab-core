def resolve(entry: str) -> griffe.Object:
    module, name = entry.split(":")
    path = ".".join([*module.split(".")[1:], name])
    obj = PACKAGE[path]
    obj = obj.final_target if isinstance(obj, griffe.Alias) else obj
    if isinstance(obj, griffe.Module):  # e.g. runner.estimate, both a module and a function
        obj = obj[name]
        obj = obj.final_target if isinstance(obj, griffe.Alias) else obj
    return obj


def signature(func: griffe.Function, name: str | None = None) -> str:
    params = []
    seen_keyword_only = False
    is_method = isinstance(func.parent, griffe.Class) and "staticmethod" not in func.labels
    for index, param in enumerate(func.parameters):
        if is_method and index == 0:
            continue
        text = param.name
        if param.kind is griffe.ParameterKind.var_positional:
            text, seen_keyword_only = f"*{text}", True
        elif param.kind is griffe.ParameterKind.var_keyword:
            text = f"**{text}"
        elif param.kind is griffe.ParameterKind.keyword_only and not seen_keyword_only:
            params.append("*")
            seen_keyword_only = True
        if param.annotation is not None:
            text += f": {param.annotation}"
        if param.default is not None and param.kind not in (
            griffe.ParameterKind.var_positional,
            griffe.ParameterKind.var_keyword,
        ):
            value = default(str(param.default))
            text += f" = {value}" if param.annotation is not None else f"={value}"
        params.append(text)
        if param.kind is griffe.ParameterKind.positional_only and not any(
            p.kind is griffe.ParameterKind.positional_only
            for p in list(func.parameters)[list(func.parameters).index(param) + 1 :]
        ):
            params.append("/")
    returns = f" -> {func.returns}" if func.returns is not None else ""
    prefix = "async def " if "async" in func.labels else "def "
    line = f"{prefix}{name or func.name}({', '.join(params)}){returns}"
    if len(line) <= 88:
        return line
    inner = "".join(f"    {p},\n" for p in params)
    return f"{prefix}{name or func.name}(\n{inner}){returns}"


def public(members: dict[str, griffe.Object | griffe.Alias]) -> list[griffe.Object]:
    found = []
    for name, member in members.items():
        if name.startswith("_") or name == "model_config" or isinstance(member, griffe.Alias):
            continue
        found.append(member)
    return found


def default(value: str) -> str:
    """A readable default, e.g. ``Field(4, gt=0)`` -> ``4``, ``list()`` -> ``[]``."""
    factories = {"list": "[]", "dict": "{}"}
    if match := re.match(r"Field\(([^,()]+)", value):
        return match.group(1)
    if match := re.match(r"field\(default_factory=(\w+)\)$", value):
        return factories.get(match.group(1), "...")
    if value in ("list()", "dict()"):
        return factories[value[:-2]]
    if "default_factory=lambda" in value or value.startswith("(lambda"):
        return "..."
    return value


def class_signature(cls: griffe.Class) -> str | None:
    """How to construct the class, e.g. ``Completion(text: str, ...)``."""
    init = cls.members.get("__init__")
    if not isinstance(init, griffe.Function) or cls.name == "Metric":
        return None  # Metric subclasses declare their own __init__
    return signature(init, cls.name).replace("def ", "", 1).removesuffix(" -> None")


def class_md(cls: griffe.Class) -> list[str]:
    parts = []
    if cls.bases:
        bases = [str(b) for b in cls.bases if str(b) not in ("ABC", "Protocol", "_Strict")]
        if any(str(b) == "Protocol" for b in cls.bases):
            parts.append("A protocol: any class with these methods works.")
        if any(str(b) == "_Strict" for b in cls.bases):
            bases = ["BaseModel"]
        if bases and bases != ["BaseModel"]:
            parts.append("Subclass of " + ", ".join(f"`{b}`" for b in bases) + ".")
    attributes = [
        m
        for m in public(cls.members)
        # Unannotated attributes are set in __init__ and shown by its signature.
        if isinstance(m, griffe.Attribute) and "property" not in m.labels and m.annotation
    ]
    properties = [
        m
        for m in public(cls.members)
        if "property" in m.labels and isinstance(m, griffe.Attribute | griffe.Function)
    ]
    methods = [
        m
        for m in public(cls.members)
        if isinstance(m, griffe.Function) and "property" not in m.labels
    ]
    if attributes:
        rows = ["| Attribute | Type | Default | Description |", "| --- | --- | --- | --- |"]
        for attr in attributes:
            doc = md(attr.docstring.value) if attr.docstring else ""
            value = f"`{default(str(attr.value))}`" if attr.value is not None else "required"
            annotation = str(attr.annotation)
            if annotation.startswith("ClassVar["):
                annotation = annotation.removeprefix("ClassVar[").removesuffix("]")
            rows.append(
                f"| `{attr.name}` | {cell(f'`{annotation}`')} | {cell(value)} | {cell(doc)} |"
            )
        parts.append("\n".join(rows))
    if properties:
        items = []
        for prop in properties:
            returns = prop.returns if isinstance(prop, griffe.Function) else prop.annotation
            doc = one_line(md(prop.docstring.value)) if prop.docstring else ""
            items.append(f"- `{prop.name}` (`{returns}`){': ' + doc if doc else ''}")
        parts.append("**Properties**\n\n" + "\n".join(items))
    for method in methods:
        doc = docstring_md(method)
        label = " (classmethod)" if "classmethod" in method.labels else ""
        parts.append(
            f"**`{method.name}`**{label}\n\n```python\n{signature(method)}\n```"
            + (f"\n\n{doc}" if doc else "")
        )
    return parts


def python_page() -> str:
    documented = {entry.split(":")[1] for _, _, entries in API for entry in entries}
    missing = sorted(set(paperlab_space.__all__) - documented - {"__version__", "export"})
    if missing:
        sys.exit(f"Add these exports to API in scripts/build_docs.py: {', '.join(missing)}")

    parts = [
        "# Python API reference",
        "Every public class and function, grouped by task.",
        "Most names import from the top-level package: `from paperlab_space import run`. "
        "Each entry shows its import path.",
    ]
    for title, intro, entries in API:
        parts += [f"## {title}", intro]
        for entry in entries:
            module, name = entry.split(":")
            obj = resolve(entry)
            code = f"from {module} import {name}"
            if isinstance(obj, griffe.Function):
                code += "\n\n" + signature(obj)
            elif isinstance(obj, griffe.Class) and (constructor := class_signature(obj)):
                code += "\n\n" + constructor
            parts += [f"### {name}", f"```python\n{code}\n```"]
            doc = docstring_md(obj)
            if doc:
                parts.append(doc)
            if isinstance(obj, griffe.Class):
                parts += class_md(obj)
    return HEADER + "\n\n".join(parts) + "\n"


# --- Main -------------------------------------------------------------------------------


def main() -> None:
    pages = {
        "config.md": config_page(),
        "metrics.md": metrics_page(),
        "python.md": python_page(),
    }
    if "--check" in sys.argv:
        stale = [n for n, text in pages.items() if _read(REFERENCE / n) != text]
        if stale:
            sys.exit(f"Out of date: {', '.join(stale)}. Run `uv run python scripts/build_docs.py`.")
        print("Reference pages are up to date.")
        return
    REFERENCE.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (REFERENCE / name).write_text(text, encoding="utf-8")
        print(f"Wrote docs/reference/{name}")


def _read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8") if path.exists() else None


if __name__ == "__main__":
    main()
