def type_name(annotation: Any) -> str:
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin in (Union, types.UnionType):
        return " or ".join(type_name(a) for a in args if a is not type(None))
    if origin is Literal:
        return ", ".join(f"`{a}`" for a in args)
    if origin is list:
        item = args[0]
        if item in SECTIONS:
            return f"list, see [`{SECTIONS[item]}`](#{SECTIONS[item]})"
        return f"list of {type_name(item)}s"
    if origin is dict:
        return "mapping"
    if annotation in SECTIONS:
        return f"object, see [`{SECTIONS[annotation]}`](#{SECTIONS[annotation]})"
    names = {str: "string", int: "integer", float: "number", bool: "boolean"}
    return names.get(annotation, getattr(annotation, "__name__", str(annotation)))


def constraints(metadata: list[Any]) -> str:
    symbols = {Ge: ("≥", "ge"), Gt: (">", "gt"), Le: ("≤", "le"), Lt: ("<", "lt")}
    found = []
    for item in metadata:
        for cls, (symbol, attr) in symbols.items():
            if isinstance(item, cls):
                found.append(f"{symbol} {getattr(item, attr)}")
    return ", ".join(found)


def scalar(value: Any) -> str:
    if value is PydanticUndefined:
        return "required"
    if value is None:
        return "none"
    if isinstance(value, BaseModel):
        return "see below"
    return f"`{json.dumps(value, ensure_ascii=False)}`"


def field_table(model: type[BaseModel]) -> str:
    griffe_class = PACKAGE[f"{model.__module__.removeprefix('paperlab_space.')}.{model.__name__}"]
    rows = ["| Field | Type | Default | Description |", "| --- | --- | --- | --- |"]
    for name, field in model.model_fields.items():
        kind = type_name(field.annotation)
        limits = constraints(field.metadata)
        member = griffe_class.members.get(name)
        doc = md(member.docstring.value) if member is not None and member.docstring else ""
        rows.append(
            f"| `{name}` | {cell(kind + (f', {limits}' if limits else ''))} | "
            f"{cell(scalar(field.default))} | {cell(doc)} |"
        )
    return "\n".join(rows)


def config_page() -> str:
    full = RunConfig.from_dict(EXAMPLE).to_yaml()
    parts = [
        "# Config file reference",
        "Every field of `run.yaml`, with its type and default.",
        "The same fields make up a `RunConfig` in Python, and the reproducibility config "
        "that every run writes has this config under its `config` key. Unknown fields are "
        "errors, so a typo never goes unnoticed.",
        "## Example",
        "A short config, and the same config with every default written out, the way it "
        "appears in the reproducibility config:",
        "```yaml\n" + yaml.safe_dump(EXAMPLE, allow_unicode=True, sort_keys=False) + "```",
        "```yaml\n" + full + "```",
        "## Top level",
        field_table(RunConfig),
    ]
    shortcuts = {
        "mapping": "`input` and `context` take one column name or a list.",
        "prompt": 'A plain string is the user message: `prompt: "Translate: {text}"`.',
        "models": "Each entry is a model ID string, or an object with options.",
        "metrics": (
            "Each entry is a metric name, or an object with options. Options can sit next to "
            "`name` (`{name: f1, average: macro}`) or under `params`. See the "
            "[metrics reference](metrics.md) for each metric's options."
        ),
    }
    for model, section in SECTIONS.items():
        parts.append(f"## {section}")
        if model.__doc__:
            parts.append(md(inspect.cleandoc(model.__doc__).split("\n\n")[0]))
        if section in shortcuts:
            parts.append(shortcuts[section])
        parts.append(field_table(model))
    return HEADER + "\n\n".join(parts) + "\n"


